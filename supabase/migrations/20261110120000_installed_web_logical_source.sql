-- TAL-62: model installed-widget captures as one logical source per venue.
--
-- Until now every page captured by the installed widget was its own
-- knowledge_sources row (type web_snapshot). This migration moves them to the
-- same shape managed web sources already use:
--
--   one web_snapshot source per venue (config.installed_web_logical = true)
--     -> one knowledge_documents row per page (capture_method installed_widget)
--       -> knowledge_chunks (source_id = logical source, document_id = page)
--
-- Chunks are moved in place (same ids, content and embeddings), so retrieval
-- keeps working without re-embedding. The migration is idempotent: it can run
-- before or after the application change and will fold any per-page rows
-- created in between into the logical source.

-- 1. One logical installed-web source per venue that has captured pages.
insert into public.knowledge_sources (theatre_id, type, name, status, source_url, config, last_synced_at)
select page.theatre_id,
       'web_snapshot',
       'Web capturada por el widget',
       'ready',
       null,
       jsonb_build_object('installed_web_logical', true, 'source_type', 'web_snapshot'),
       max(page.last_synced_at)
  from public.knowledge_sources as page
 where page.type = 'web_snapshot'
   and coalesce(page.config->>'installed_web_logical', 'false') <> 'true'
   and not exists (
     select 1
       from public.knowledge_sources as logical
      where logical.theatre_id = page.theatre_id
        and logical.type = 'web_snapshot'
        and logical.config->>'installed_web_logical' = 'true'
   )
 group by page.theatre_id;

-- 2. Map every per-page source to its venue's logical source.
create temporary table installed_web_page_map on commit drop as
select page.id as page_source_id,
       page.theatre_id,
       logical.id as logical_source_id,
       public.canonicalize_knowledge_source_url(page.source_url) as canonical_url,
       page.name,
       page.status,
       page.config,
       page.last_synced_at,
       page.last_error,
       page.created_at,
       row_number() over (
         partition by page.theatre_id, public.canonicalize_knowledge_source_url(page.source_url)
         order by page.last_synced_at desc nulls last, page.created_at desc
       ) as url_rank
  from public.knowledge_sources as page
  join public.knowledge_sources as logical
    on logical.theatre_id = page.theatre_id
   and logical.type = 'web_snapshot'
   and logical.config->>'installed_web_logical' = 'true'
 where page.type = 'web_snapshot'
   and coalesce(page.config->>'installed_web_logical', 'false') <> 'true'
   and page.source_url is not null;

-- Structured events hang off (document, source); none exist for per-page
-- installed sources today. If any appear before this runs they are dropped
-- here and regenerated by the next capture, instead of blocking the move.
delete from public.programme_events as event
 using installed_web_page_map as map
 where event.source_id = map.page_source_id;

delete from public.knowledge_documents as document
 using installed_web_page_map as map
 where document.source_id = map.page_source_id;

-- 3. One document per canonical URL under the logical source.
insert into public.knowledge_documents (
  theatre_id, source_id, canonical_url, fetched_url, title, status, capture_method,
  content_hash, last_discovered_at, last_fetched_at, last_error, metadata, created_at
)
select map.theatre_id,
       map.logical_source_id,
       map.canonical_url,
       map.canonical_url,
       nullif(coalesce(map.config->>'page_title', map.name), ''),
       case map.status
         when 'ready' then 'ready'
         when 'error' then 'error'
         else 'pending'
       end,
       'installed_widget',
       map.config->>'content_hash',
       coalesce(
         (map.config->>'last_seen_at')::timestamptz,
         (map.config->>'registered_at')::timestamptz,
         map.created_at
       ),
       map.last_synced_at,
       map.last_error,
       (map.config - 'capture_url' - 'source_url' - 'installed_web_logical')
         || jsonb_build_object('legacy_source_id', map.page_source_id),
       map.created_at
  from installed_web_page_map as map
 where map.url_rank = 1
on conflict (source_id, canonical_url) do nothing;

-- 4. Move chunks of the winning page for each URL onto its document.
--    Chunks of duplicate URLs stay on their page source and are removed with it.
update public.knowledge_chunks as chunk
   set source_id = map.logical_source_id,
       document_id = document.id
  from installed_web_page_map as map
  join public.knowledge_documents as document
    on document.source_id = map.logical_source_id
   and document.theatre_id = map.theatre_id
   and document.canonical_url = map.canonical_url
 where chunk.source_id = map.page_source_id
   and chunk.theatre_id = map.theatre_id
   and map.url_rank = 1;

-- Operational history follows the page to the logical source.
update public.knowledge_source_support_requests as request
   set source_id = map.logical_source_id
  from installed_web_page_map as map
 where request.source_id = map.page_source_id;

update public.knowledge_sync_runs as run
   set source_id = map.logical_source_id
  from installed_web_page_map as map
 where run.source_id = map.page_source_id;

-- 5. Remove the per-page sources (now empty, or duplicates of a moved URL).
delete from public.knowledge_sources as page
 using installed_web_page_map as map
 where page.id = map.page_source_id;

-- Per-page rows without a URL cannot become documents and carry no usable page.
delete from public.knowledge_sources as page
 where page.type = 'web_snapshot'
   and page.source_url is null
   and coalesce(page.config->>'installed_web_logical', 'false') <> 'true';

-- 6. Invariant: at most one installed-web source per venue from now on.
create unique index if not exists knowledge_sources_one_installed_web_per_theatre_idx
  on public.knowledge_sources(theatre_id)
  where type = 'web_snapshot';

create index if not exists knowledge_documents_installed_widget_idx
  on public.knowledge_documents(source_id, last_discovered_at desc)
  where capture_method = 'installed_widget';

