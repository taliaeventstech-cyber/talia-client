import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const migration = readFileSync(
  join(process.cwd(), 'supabase/migrations/20260905120000_backstage_multichannel_response_traces.sql'),
  'utf8',
)

describe('Backstage multichannel response trace migration', () => {
  it('unifies all supported attention channels with global pagination', () => {
    expect(migration).toContain("'web'::text as channel")
    expect(migration).toContain("'email'::text as channel")
    expect(migration).toContain("'whatsapp'::text as channel")
    expect(migration).toContain('order by created_at desc, id desc')
    expect(migration).toContain('limit p_limit')
    expect(migration).toContain('offset p_offset')
  })

  it('only includes AI-authored WhatsApp messages', () => {
    expect(migration).toContain("outbound.metadata ->> 'agent' = 'whatsapp_agent'")
    expect(migration).toContain("outbound.metadata ? 'agent_reply_to_message_id'")
    expect(migration).toContain("coalesce(outbound.metadata ->> 'operator_reply', 'false') <> 'true'")
  })

  it('only includes drafts generated by the email agent', () => {
    expect(migration).toContain("draft.metadata ->> 'source' = 'email_agent'")
  })

  it('is restricted to the service role', () => {
    expect(migration).toContain('security definer')
    expect(migration).toContain('revoke all on function public.get_backstage_response_traces')
    expect(migration).toContain('grant execute on function public.get_backstage_response_traces')
    expect(migration).toContain('to service_role')
  })
})
